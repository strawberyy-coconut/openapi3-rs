#[test]
fn roundtrip_full_coverage() {
    let api = build_full_coverage();
    let json = serde_json::to_string_pretty(&api).expect("serialize");
    let back: OpenAPI = serde_json::from_str(&json).expect("deserialize");

    // ---- Spot-check key features survived the roundtrip ----

    // Root fields
    assert_eq!(back.self_uri.as_deref(), Some("https://example.com/api/openapi.json"));
    assert!(back.json_schema_dialect.is_some());
    assert!(back.external_docs.is_some());
    assert!(back.webhooks.as_ref().unwrap().contains_key("newPet"));

    // Servers with variables
    let sv = &back.servers.as_ref().unwrap()[0];
    assert_eq!(sv.name.as_deref(), Some("primary"));
    let env = sv.variables.as_ref().unwrap().get("environment").unwrap();
    assert_eq!(env.default, "api");

    // Tags with 3.2 fields
    let tags = back.tags.as_ref().unwrap();
    assert_eq!(tags[0].kind.as_deref(), Some("nav"));
    assert_eq!(tags[1].parent.as_deref(), Some("pets"));

    // Global security
    let sec = back.security.as_ref().unwrap();
    assert!(sec[0].contains_key("petstore_oauth"));

    // Boolean schemas
    let comp = back.components.as_ref().unwrap();
    let schemas = comp.schemas.as_ref().unwrap();
    assert!(schemas["AllowAll"].is_bool());
    assert!(schemas["AllowNone"].is_bool());
    assert_eq!(schemas["AllowAll"].as_bool(), Some(true));
    assert_eq!(schemas["AllowNone"].as_bool(), Some(false));

    // Discriminator + XML + externalDocs + example on schema
    let pet_obj = schemas["Pet"].as_object().unwrap();
    assert!(pet_obj.discriminator.is_some());
    assert_eq!(pet_obj.discriminator.as_ref().unwrap().property_name, "petType");
    assert!(pet_obj.xml.is_some());
    assert!(pet_obj.external_docs.is_some());
    assert!(pet_obj.examples().is_some());

    // All Components sub-maps
    assert!(comp.responses.as_ref().unwrap().contains_key("NotFound"));
    assert!(comp.parameters.as_ref().unwrap().contains_key("offsetParam"));
    assert!(comp.examples.as_ref().unwrap().contains_key("CatExample"));
    assert!(comp.request_bodies.as_ref().unwrap().contains_key("PetBody"));
    assert!(comp.headers.as_ref().unwrap().contains_key("X-Rate-Limit"));
    assert!(comp.security_schemes.as_ref().unwrap().contains_key("api_key"));
    assert!(comp.security_schemes.as_ref().unwrap().contains_key("petstore_oauth"));
    assert!(comp.links.as_ref().unwrap().contains_key("GetPet"));
    assert!(comp.callbacks.as_ref().unwrap().contains_key("StatusCallback"));
    assert!(comp.path_items.as_ref().unwrap().contains_key("HealthPath"));
    assert!(comp.media_types.as_ref().unwrap().contains_key("JsonPatch"));

    // All HTTP methods on /pets
    let paths = back.paths.as_ref().unwrap();
    let pets = paths["/pets"].as_item().unwrap();
    assert!(pets.get.is_some());
    assert!(pets.put.is_some());
    assert!(pets.post.is_some());
    assert!(pets.delete.is_some());
    assert!(pets.options.is_some());
    assert!(pets.head.is_some());
    assert!(pets.additional_operations.as_ref().unwrap().contains_key("COPY"));
    assert!(pets.servers.is_some());
    assert!(pets.parameters.is_some());

    // Deprecated operation
    assert_eq!(pets.delete.as_ref().unwrap().deprecated, Some(true));

    // Parameter styles and locations
    let list_op = pets.get.as_ref().unwrap();
    let filter_param = list_op.parameters.as_ref().unwrap()[0].as_item().unwrap();
    assert_eq!(filter_param.style, Some(Style::Form));
    assert_eq!(filter_param.explode, Some(true));

    // Path param + cookie param + externalDocs on operation
    let pet_path = paths["/pets/{petId}"].as_item().unwrap();
    let get_op = pet_path.get.as_ref().unwrap();
    assert!(get_op.external_docs.is_some());
    let params = get_op.parameters.as_ref().unwrap();
    assert_eq!(params[0].as_item().unwrap().location, ParameterIn::Path);
    assert_eq!(params[1].as_item().unwrap().location, ParameterIn::Cookie);
    assert!(get_op.callbacks.is_some());

    // Querystring parameter with content
    let search = paths["/pets/search"].as_item().unwrap();
    let search_op = search.get.as_ref().unwrap();
    let qs = search_op.parameters.as_ref().unwrap()[0].as_item().unwrap();
    assert_eq!(qs.location, ParameterIn::Querystring);
    assert!(qs.content.is_some());

    // Streaming media type (itemSchema)
    let stream_path = paths["/pets/stream"].as_item().unwrap();
    let stream_op = stream_path.get.as_ref().unwrap();
    let stream_body = &stream_op.responses.responses["200"].as_item().unwrap();
    let stream_content = stream_body.content.as_ref().unwrap();
    assert!(stream_content["application/jsonl"].as_item().unwrap().item_schema.is_some());

    // Multipart encoding
    let avatar_path = paths["/pets/{petId}/avatar"].as_item().unwrap();
    let upload_op = avatar_path.post.as_ref().unwrap();
    let upload_body = upload_op.request_body.as_ref().unwrap().as_item().unwrap();
    let upload_content = upload_body.content["multipart/form-data"].as_item().unwrap();
    let enc = upload_content.encoding.as_ref().unwrap();
    assert!(enc.contains_key("avatar"));
    assert!(enc.contains_key("caption"));

    // References (round-trip survives $ref)
    let list_responses = &list_op.responses;
    assert!(list_responses.default.is_some());
    assert!(list_responses.responses["200"].as_item().unwrap().headers.is_some());

    // Security on operation
    assert!(list_op.security.is_some());

    // OAuth2 device_authorization flow (3.2)
    let oauth = comp.security_schemes.as_ref().unwrap()["petstore_oauth"]
        .as_item().unwrap();
    let flows = oauth.flows.as_ref().unwrap();
    assert!(flows.device_authorization.is_some());
    assert!(flows.implicit.is_some());

    // Reusable Example with dataValue
    let ex = comp.examples.as_ref().unwrap()["CatExample"].as_item().unwrap();
    assert!(ex.data_value.is_some());

    // Link with server
    let link = comp.links.as_ref().unwrap()["GetPet"].as_item().unwrap();
    assert!(link.server.is_some());
    assert!(link.parameters.is_some());

    // Callback roundtrip
    let cb = comp.callbacks.as_ref().unwrap()["StatusCallback"].as_item().unwrap();
    assert!(cb.contains_key("{$request.body#/callbackUrl}"));
}

