//! Integration tests for `openapi3-rs`.
//!
//! Two test functions:
//! - `roundtrip_full_coverage` — constructs a document exercising **every type**
//!   and feature in the crate, then round-trips through JSON.
//! - `validate_against_swagger_validator` — a valid subset that passes the
//!   official Swagger validator (requires network; `#[ignore]` by default).
//!
//! Run with:
//! ```bash
//! cargo test                          # local tests
//! cargo test -- --ignored             # includes network-dependent validation
//! ```

use indexmap::IndexMap;
