#[test]
fn validate_against_swagger_validator() {
    let api = build_petstore();
    let json = serde_json::to_string_pretty(&api).expect("serialize");

    let output = std::process::Command::new("curl")
        .args([
            "-s", "-X", "POST",
            "-H", "Content-Type: application/json",
            "-d", &json,
            "https://validator.swagger.io/validator/debug",
        ])
        .output()
        .expect("curl to validator");

    assert!(output.status.success(),
        "curl failed: {}", String::from_utf8_lossy(&output.stderr));

    let body: Value = serde_json::from_slice(&output.stdout)
        .expect("parse validator response");

    let errors = body.get("schemaValidationMessages")
        .and_then(|v| v.as_array())
        .map(|a| a.as_slice())
        .unwrap_or(&[]);

    if !errors.is_empty() {
        eprintln!("Validator returned {} error(s):", errors.len());
        for err in errors {
            eprintln!("  - {}", serde_json::to_string_pretty(err).unwrap());
        }
        eprintln!("\nSubmitted document:\n{json}");
    }

    assert!(errors.is_empty(),
        "OpenAPI document failed swagger validation with {} error(s)", errors.len());
}

