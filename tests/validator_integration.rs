// ---------------------------------------------------------------------------
// Test struct with schemars-derive for generated schema
// ---------------------------------------------------------------------------

#[derive(Debug, JsonSchema)]
#[allow(dead_code)]
struct NewPet {
    /// Name of the pet
    name: String,
    /// Tag / category
    #[schemars(default)]
    tag: Option<String>,
}

// ---------------------------------------------------------------------------
// Helper: convert a schemars::Schema into our Schema type
// ---------------------------------------------------------------------------

fn from_schemars(s: schemars::Schema) -> Schema {
    let value = s.to_value();
    serde_json::from_value(value).expect("schemars::Schema -> openapi3_rs::Schema")
}

// ---------------------------------------------------------------------------
// JSON response helper
// ---------------------------------------------------------------------------

fn json_response(desc: &str, schema_ref: &str) -> Response {
    Response {
        description: desc.into(),
        content: Some({
            let mut c = IndexMap::new();
            c.insert("application/json".into(), RefOr::Item(MediaType {
                schema: Some(RefOr::Item(Schema::Object(SchemaObject {
                    schema_data: {
                        let mut m = JsonMap::new();
                        m.insert("$ref".into(), Value::String(schema_ref.into()));
                        m
                    },
                    ..Default::default()
                }))),
                ..Default::default()
            }));
            c
        }),
        ..Default::default()
    }
}

